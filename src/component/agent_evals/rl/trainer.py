logger = get_logger(__name__)

#: ``metrics.csv`` columns, one row per optimizer step: the step number, then TRL's step log under
#: TRL's own names. Keys are stable forever once a run has used them (AGENTS.md §4.5).
STEP_COLUMNS = (
    "step",
    "reward",
    "reward_std",
    "kl",
    "loss",
    "grad_norm",
    "learning_rate",
    "entropy",
    "frac_reward_zero_std",
    "completions/mean_length",
    "completions/min_length",
    "completions/max_length",
    "completions/clipped_ratio",
    "completions/mean_terminated_length",
    "num_tokens",
    "step_time",
)

#: TRL's per-term step log, added after ``STEP_COLUMNS`` for a reward of several terms, so each
#: term is watched every step (D-134, D-135).
_TERM_COLUMNS = ("rewards/{name}/mean", "rewards/{name}/std")

#: Every step must report these: rising reward with diverging KL is the reward-exploitation
#: signature (AGENTS.md §4.6).
_REQUIRED_STEP_KEYS = ("reward", "kl")

#: Log, and so write a metrics row, after every optimizer step (AGENTS.md §4.6).
_LOG_EVERY_STEP = 1

#: Rollouts are generated by TRL's built-in transformers path, not by vLLM inside training (D-053).
_USE_VLLM = False

#: Folder inside the run's adapter directory that holds the final adapter.
_FINAL_ADAPTER = "final"


class TrainingError(RuntimeError):
    """Raised for a config that cannot train, or a training step that breaks the log contract."""


@dataclass(frozen=True, slots=True)
class ResumePoint:
    """Where an interrupted run continues from.

    Attributes:
        run_id: The first run of the chain; every continuation names it.
        adapter_dir: That run's adapter directory, where every continuation writes checkpoints.
        checkpoint: The checkpoint training continues from.
    """

    run_id: str
    adapter_dir: Path
    checkpoint: Path


def latest_checkpoint(adapter_dir: Path) -> Path:
    """The highest-step checkpoint in an adapter directory.

    Args:
        adapter_dir: A run's adapter directory.

    Returns:
        Its ``checkpoint-<step>`` folder with the largest step.

    Raises:
        TrainingError: If it holds no checkpoint.
    """
    steps = {
        int(path.name.removeprefix("checkpoint-")): path
        for path in adapter_dir.glob("checkpoint-*")
        if path.is_dir() and path.name.removeprefix("checkpoint-").isdigit()
    }
    if not steps:
        raise TrainingError(f"no checkpoint to resume from in {adapter_dir}")
    return steps[max(steps)]


def question_seed(seed: int, example_id: str) -> int:
    """The seed one question's worked examples are drawn from under ``per_question`` (D-139).

    Derived from the run's seed and the question's ID alone, so a question gets the same draw
    whatever the order of the pool, and a resumed run rebuilds the same prompts.

    Args:
        seed: The run's worked-example seed.
        example_id: The question's ID.

    Returns:
        A seed in [0, MAX_SEED].
    """
    digest = hashlib.sha256(f"{seed}:{example_id}".encode()).digest()
    return int.from_bytes(digest[:8], "big") % (MAX_SEED + 1)


def training_dataset(
    examples: Sequence[Example],
    template: InitialPromptMixin,
    seed: int = 0,
    per_question: bool = False,
) -> Dataset:
    """Turn examples into TRL's conversational prompt dataset, with the columns the reward reads.

    Args:
        examples: Training examples in the evidence-paired schema.
        template: The Generator template training renders: the dataset's T0 template unless
            ``training.prompt_template`` names another (D-053, D-136).
        seed: Seed a few-shot template draws its worked examples from, once for every example,
            as evaluation draws them per run (D-118). A zero-shot template ignores it.
        per_question: Draw each example's worked examples afresh, from
            :func:`question_seed` (D-139), instead of once for every example.

    Returns:
        A dataset with ``prompt`` (the messages T0 sends: any worked examples as earlier turns,
        then one user message), ``evidence``, ``reference``, ``gold`` and ``id``, aligned row by
        row.
    """
    seeds = [question_seed(seed, e.id) if per_question else seed for e in examples]
    return Dataset.from_dict(
        {
            "prompt": [template.messages(e, s) for e, s in zip(examples, seeds, strict=True)],
            "evidence": [e.evidence for e in examples],
            "reference": [e.reference for e in examples],
            "gold": [e.gold for e in examples],
            "id": [e.id for e in examples],
        }
    )


def step_columns(reward_names: Sequence[str]) -> tuple[str, ...]:
    """``metrics.csv`` columns for a run: ``STEP_COLUMNS``, plus each term's mean and spread when
    the reward has several terms.

    Args:
        reward_names: The reward functions' names, in the order TRL receives them.

    Returns:
        The columns, in order. A single reward keeps exactly ``STEP_COLUMNS``.
    """
    if len(reward_names) < 2:
        return STEP_COLUMNS
    terms = tuple(column.format(name=n) for n in reward_names for column in _TERM_COLUMNS)
    return STEP_COLUMNS + terms


def grpo_args(cfg: ExperimentConfig, output_dir: Path) -> GRPOConfig:
    """TRL's GRPO arguments, every result-changing value taken from the config.

    Args:
        cfg: Resolved config with a ``training`` group.
        output_dir: Where TRL writes checkpoints for this run.

    Returns:
        The GRPO arguments. The run's seed is passed through, so the seed TRL sets matches the
        one ``seeding.py`` already set; the completion cap is ``sampling.max_tokens`` (D-012).
        Completions are generated one forward pass at a time, ``per_device_train_batch_size`` of
        them, as the Q-004 cells measured: TRL's default generates a whole optimizer step's
        completions at once, which ran out of memory (D-063).

    Raises:
        TrainingError: If the config has no ``training`` group.
    """
    t = _require(cfg.training, "training")
    return GRPOConfig(
        output_dir=str(output_dir),
        seed=cfg.run.seed,
        beta=t.beta,
        loss_type=t.loss_type,
        scale_rewards=t.scale_rewards,
        epsilon=t.epsilon,
        num_iterations=t.num_iterations,
        num_generations=t.num_generations,
        per_device_train_batch_size=t.per_device_train_batch_size,
        generation_batch_size=t.per_device_train_batch_size,
        gradient_accumulation_steps=t.gradient_accumulation_steps,
        max_steps=t.max_steps,
        save_strategy="steps",
        save_steps=t.save_steps,
        learning_rate=t.learning_rate,
        lr_scheduler_type=t.lr_scheduler_type,
        warmup_steps=t.warmup_steps,
        optim=t.optim,
        max_grad_norm=t.max_grad_norm,
        gradient_checkpointing=t.gradient_checkpointing,
        mask_truncated_completions=t.mask_truncated_completions,
        multi_objective_aggregation=t.multi_objective_aggregation,
        reward_weights=_weights(cfg),
        temperature=t.temperature,
        top_p=t.top_p,
        top_k=t.top_k,
        repetition_penalty=t.repetition_penalty,
        max_completion_length=cfg.sampling.max_tokens,
        generation_kwargs=(
            {"min_new_tokens": cfg.sampling.max_tokens} if t.force_full_completions else None
        ),
        bf16=t.compute_dtype == "bfloat16",
        fp16=t.compute_dtype == "float16",
        logging_steps=_LOG_EVERY_STEP,
        report_to="none",
        use_vllm=_USE_VLLM,
    )


def lora_config(cfg: TrainingConfig) -> LoraConfig:
    """The LoRA adapter T5 trains.

    Args:
        cfg: Training configuration.

    Returns:
        A causal-LM LoRA config over ``cfg.lora_target_modules``.
    """
    return LoraConfig(
        r=cfg.lora_rank,
        lora_alpha=cfg.lora_alpha,
        lora_dropout=cfg.lora_dropout,
        target_modules=cfg.lora_target_modules,
        task_type="CAUSAL_LM",
    )


class StepMetricsCallback(TrainerCallback):
    """Writes one ``metrics.csv`` row per optimizer step from TRL's step log.

    Args:
        writer: The run's metrics writer.
        columns: The row's columns, ``step`` first; :func:`step_columns`.

    Attributes:
        last_row: The most recent row written, or None before the first step.
    """

    def __init__(self, writer: MetricsWriter, columns: Sequence[str] = STEP_COLUMNS) -> None:
        self._writer = writer
        self._columns = tuple(columns)
        self.last_row: dict[str, Any] | None = None

    def on_log(
        self, args: Any, state: Any, control: Any, logs: dict[str, Any] | None = None, **kwargs: Any
    ) -> None:
        """Write the step's row. The end-of-training summary log carries no reward and is skipped.

        Raises:
            TrainingError: If a step log lacks reward or KL.
        """
        if not logs or "reward" not in logs:
            return
        missing = [key for key in _REQUIRED_STEP_KEYS if logs.get(key) is None]
        if missing:
            raise TrainingError(
                f"step {state.global_step} logged no {missing}; reward and KL are required every "
                "step (AGENTS.md §4.6), and TRL logs KL only when training.beta > 0"
            )
        row: dict[str, Any] = {"step": state.global_step}
        row.update({key: logs.get(key) for key in self._columns[1:]})
        self._writer.write(row)
        self.last_row = row


class GRPOTrainingRun:
    """One T5 training run: GRPO on a LoRA adapter, written to ``results/<run_id>/``.

    The run is named ``<config name>_<backbone>``, so a measurement run and a training run of
    the same backbone never share a name.

    Args:
        cfg: Resolved config with ``data``, ``reward`` and ``training`` groups.
        backbone: ``model_registry.csv`` name of the backbone to train.
        repo_root: Repository root; the registry, ``.env`` and ``results/`` resolve against it.
        resume: Where to continue an interrupted run from; None starts a new run. Build it with
            :meth:`resuming` rather than by hand.

    Raises:
        TrainingError: If a required config group is missing.
    """

    def __init__(
        self,
        cfg: ExperimentConfig,
        backbone: str,
        repo_root: Path,
        resume: ResumePoint | None = None,
    ) -> None:
        missing = [name for name in ("data", "reward", "training") if getattr(cfg, name) is None]
        if missing:
            raise TrainingError(f"training needs the config group(s) {missing}")
        self._cfg = cfg
        self._backbone_name = backbone
        self._repo_root = repo_root
        self._resume = resume

    @classmethod
    def resuming(cls, run_dir: Path, repo_root: Path) -> GRPOTrainingRun:
        """Continue an interrupted run from its latest checkpoint, with its own resolved config.

        Args:
            run_dir: The interrupted run's ``results/<run_id>/``, or any continuation of it.
            repo_root: Repository root.

        Returns:
            A run that continues the chain when :meth:`run` is called.

        Raises:
            TrainingError: If the run left no checkpoint.
            ConfigError: If its resolved config no longer loads.
        """
        manifest = json.loads((run_dir / "manifest.json").read_text(encoding="utf-8"))
        backbone = manifest["backbone"]["name"]
        adapter_dir = Path(manifest["adapter_dir"])
        cfg = load_config(run_dir / "config.resolved.yaml")
        cfg = dataclasses.replace(cfg, name=cfg.name.removesuffix(f"_{backbone}"))
        first = manifest.get("resumed_from") or manifest["run_id"]
        resume = ResumePoint(first, adapter_dir, latest_checkpoint(adapter_dir))
        return cls(cfg, backbone, repo_root, resume)

    @property
    def config(self) -> ExperimentConfig:
        """The config this run trains with."""
        return self._cfg

    def run(self) -> Path:
        """Check the training gate, train, save the adapter and record the run.

        Returns:
            The run directory written.

        Raises:
            DatasetError: For a Tier 3, evaluation-only or non-training split, before any model
                loads.
            TrainingError, ConfigError, RegistryError, ModelRegistryError, RewardError,
            MetricError, ServingError: From the component that failed. Failures after the run
                directory exists are recorded in its ``summary.json`` too.
        """
        cfg = self._cfg
        adapter = self._build_adapter()
        adapter.assert_trainable(cfg.data.split)
        template = self._template()
        seed = worked_examples_seed(cfg)
        per_question = cfg.training.worked_examples_draw == "per_question"
        examples = [adapter.as_example(row) for row in adapter.build()]
        dataset = training_dataset(examples, template, seed, per_question)

        load_env_file(self._repo_root / cfg.serving.env_file)
        registry = load_model_registry(self._repo_root / cfg.serving.model_registry)
        backbone = select_backbone(registry, self._backbone_name)
        named = dataclasses.replace(cfg, name=f"{cfg.name}_{backbone.name}")
        now = datetime.now()
        if self._resume is None:
            output_dir = Path(cfg.training.adapter_root).expanduser() / make_run_id(
                named.name, named.run.seed, now
            )
        else:
            output_dir = self._resume.adapter_dir
        args = grpo_args(cfg, output_dir)
        peft_config = lora_config(cfg.training)
        prompt = {template.name: template.label}
        if per_question:
            # How many questions drew each ordered pair, by the examples' source IDs (D-139).
            draws = Counter(
                ",".join(d.source_id for d in template.drawn_examples(question_seed(seed, e.id)))
                for e in examples
            )
            if any(draws):
                prompt[f"{template.name}_examples"] = "per_question"
                prompt[f"{template.name}_example_draws"] = dict(sorted(draws.items()))
        else:
            drawn = template.drawn_examples(seed)
            if drawn:
                prompt[f"{template.name}_examples"] = ",".join(e.source_id for e in drawn)
        manifest = {
            "backbone": dataclasses.asdict(backbone),
            "task": cfg.data.name,
            "split": cfg.data.split,
            "n_examples": len(examples),
            "prompt_templates": {"generator": prompt},
            "reward": self._reward_manifest(),
            "grpo_args": args.to_dict(),
            "lora": peft_config.to_dict(),
            "adapter_dir": str(output_dir),
        }
        if self._resume is not None:
            manifest["resumed_from"] = self._resume.run_id
            manifest["resumed_checkpoint"] = str(self._resume.checkpoint)
            logger.info("continuing %s from %s", self._resume.run_id, self._resume.checkpoint)
        with RunDirectory(named, self._repo_root, now=now, manifest_extra=manifest) as run:
            self._train(run, backbone, dataset, args, peft_config, output_dir)
        return run.path

    def _train(
        self,
        run: RunDirectory,
        backbone: BackboneSpec,
        dataset: Dataset,
        args: GRPOConfig,
        peft_config: LoraConfig,
        output_dir: Path,
    ) -> None:
        rewards = self._build_rewards()
        model, tokenizer = self._load_model(backbone)
        callback = StepMetricsCallback(run.metrics, step_columns([r.name for r in rewards]))
        trainer = GRPOTrainer(
            model=model,
            reward_funcs=[as_trl_reward(reward) for reward in rewards],
            args=args,
            train_dataset=dataset,
            processing_class=tokenizer,
            peft_config=peft_config,
            callbacks=[callback],
        )
        checkpoint = None if self._resume is None else str(self._resume.checkpoint)
        output = trainer.train(resume_from_checkpoint=checkpoint)
        final = output_dir / _FINAL_ADAPTER
        trainer.save_model(str(final))
        runtime_s = float(output.metrics["train_runtime"])
        last = callback.last_row or {}
        run.add_summary(
            steps_completed=trainer.state.global_step,
            train_runtime_s=round(runtime_s, 3),
            training_gpu_hours=round(runtime_s / 3600 * trainer.args.n_gpu, 4),
            adapter_path=str(final),
            final_reward=last.get("reward"),
            final_kl=last.get("kl"),
        )
        logger.info("adapter saved to %s after %d steps", final, trainer.state.global_step)

    def _build_adapter(self) -> DatasetAdapter:
        """The dataset adapter for ``cfg.data``. Tests substitute an offline one."""
        return DATASETS.build(self._cfg.data.name, self._cfg.data)

    def _template(self) -> InitialPromptMixin:
        try:
            return training_template(self._cfg)
        except AgentError as exc:
            raise TrainingError(str(exc)) from None

    def _reward_classes(self) -> list[type[MetricReward]]:
        classes = []
        for name in self._cfg.reward.names:
            reward_class = REWARDS.get(name)
            if not issubclass(reward_class, MetricReward):
                raise TrainingError(f"reward {name!r} does not wrap a metric")
            classes.append(reward_class)
        return classes

    def _reward_manifest(self) -> dict[str, Any]:
        """The reward as the manifest records it: one name, or every term and how they combine."""
        reward = self._cfg.reward
        classes = self._reward_classes()
        if reward.terms is None:
            return {"name": reward.name, "metric": classes[0].METRIC}
        return {
            "terms": [
                {"name": name, "metric": reward_class.METRIC}
                for name, reward_class in zip(reward.terms, classes, strict=True)
            ],
            "weights": list(reward.weights),
            "aggregation": self._cfg.training.multi_objective_aggregation,
            "citation_judge": self._cfg.metrics.citation.judge,
        }

    def _build_rewards(self) -> list[Reward]:
        """Every configured reward term, in order. Each metric is built once and shared by the
        terms that read it, so its model loads once and scores each batch once. Tests substitute
        stub metrics through :meth:`_build_metric`."""
        shared: dict[str, SharedMetric] = {}
        rewards: list[Reward] = []
        for name, reward_class in zip(self._cfg.reward.names, self._reward_classes(), strict=True):
            if reward_class.METRIC not in shared:
                shared[reward_class.METRIC] = SharedMetric(self._build_metric(reward_class.METRIC))
            rewards.append(
                reward_class(
                    self._cfg.reward.single(name),
                    shared[reward_class.METRIC],
                    strip_citations=self._cfg.data.strip_citations,
                )
            )
        return rewards

    def _build_metric(self, name: str) -> Any:
        """One registered metric, built once. Tests substitute a stub."""
        return METRICS.build(name, self._cfg.metrics)

    def _load_model(self, backbone: BackboneSpec) -> tuple[Any, Any]:
        """The 4-bit backbone and its tokenizer. Tests substitute a tiny model built in memory."""
        return load_training_model(backbone, self._cfg.training)


def _weights(cfg: ExperimentConfig) -> list[float] | None:
    """TRL's ``reward_weights``: the terms' weights, or None (weight 1) for a single reward."""
    if cfg.reward is None or cfg.reward.weights is None:
        return None
    return list(cfg.reward.weights)


def _require(value: Any, group: str) -> Any:
    if value is None:
        raise TrainingError(f"training needs the config group {group!r}")
    return value


def main(argv: list[str] | None, repo_root: Path) -> int:
    """Command-line wrapper: run one training run, or continue an interrupted one.

    Args:
        argv: Arguments, excluding the program name.
        repo_root: Repository root.

    Returns:
        0 when training finished, 1 otherwise. A run that fails after its directory exists still
        records the failure, or the OOM, in its ``summary.json``.
    """
    parser = argparse.ArgumentParser(description="Train T5 with GRPO and write results/<run_id>/.")
    parser.add_argument("--config", type=Path, help="training config YAML")
    parser.add_argument("--backbone", help="model_registry.csv name")
    parser.add_argument("--set", dest="overrides", action="append", help="key.path=value")
    parser.add_argument("--resume", type=Path, help="results/<run_id> of an interrupted run")
    args = parser.parse_args(argv)
    if args.resume is not None and (args.config or args.backbone or args.overrides):
        parser.error("--resume takes no other option: the run continues with its own config")
    if args.resume is None and not (args.config and args.backbone):
        parser.error("--config and --backbone are required unless --resume is given")
    try:
        if args.resume is not None:
            training = GRPOTrainingRun.resuming(args.resume, repo_root)
        else:
            cfg = load_config(args.config, args.overrides)
            training = GRPOTrainingRun(cfg, args.backbone, repo_root)
        cfg = training.config
        configure_logging(cfg.logging)
        path = training.run()
    except Exception:  # the one top-level catch (AGENTS.md §6); the run dir holds the details
        configure_logging(LoggingConfig())
        logger.exception("training did not complete")
        return 1
    configure_logging(cfg.logging)
    logger.info("training finished: %s", path)
    return 0
