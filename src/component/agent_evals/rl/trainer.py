"""T5 training: one GRPO run on a LoRA adapter over the 4-bit base (D-046, D-047).

The dataset's training gate runs before anything else, so a Tier 3 or evaluation-only split is
refused before a model loads (AGENTS.md §4.2). The policy is trained with TRL's ``GRPOTrainer`` on
the T0 prompt, rewarded by a registered reward that wraps a validated metric (D-048). Every
optimizer step writes one ``metrics.csv`` row carrying reward and KL (AGENTS.md §4.6).

The adapter is written to ``training.adapter_root/<run_id>/``, outside the repository, because
weights never go into the committed ``results/`` (D-053). ``summary.json`` records its path and
the GPU-hours the run took, which the H5a break-even divides by (AGENTS.md §5).

An interrupted run continues from its latest checkpoint with ``--resume results/<run_id>``.
The continuation reloads that run's own resolved config, writes its checkpoints into the same
adapter directory, and is recorded as a new run directory whose manifest names the first run
(D-059); no earlier run directory is ever changed.

This module imports TRL, PEFT and transformers, so the package does not import it on start-up;
``src/run_training.py`` and the tests import it directly.
"""

